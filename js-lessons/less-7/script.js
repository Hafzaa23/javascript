//math object

let outPut;

//square root

outPut = Math.sqrt(25);
console.log(outPut);

//obsolute value
outPut = Math.abs(-10);
console.log(outPut);

//rounded

outPut = Math.round(4.5);
console.log(outPut);

//rounded up (ceiling)
outPut = Math.ceil(4.2);
console.log(outPut);

//rounded down (floor)

outPut = Math.floor(5.9);
console.log(outPut);

//exponent (power )
outPut = Math.pow(5, 2);
console.log(outPut);

//minimum number
outPut = Math.min(3, 5, 9, 7);
// maximum number
outPut = Math.max(6.6, 8, 5, 2);
console.log(outPut);

//random number (0 and 1)
outPut = Math.random();
console.log(outPut);

